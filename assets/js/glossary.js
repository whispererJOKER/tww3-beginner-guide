(function () {
  'use strict';
  const root = document.getElementById('glossary-root');
  if (!root) return;
  const input = document.getElementById('glossary-search');
  const chips = document.querySelectorAll('.filter[data-cat]');
  const count = document.getElementById('glossary-count');
  let cat = '全部';
  let q = '';

  function render() {
    const list = TERMS.filter(x => {
      if (cat !== '全部' && x.cat !== cat) return false;
      if (q) {
        const hay = (x.t + x.en + x.d).toLowerCase();
        if (!hay.includes(q.toLowerCase())) return false;
      }
      return true;
    });
    if (count) count.textContent = list.length + ' 条';
    if (!list.length) {
      root.innerHTML = '<div class="empty" style="grid-column:1/-1">没有找到匹配的词条。</div>';
      return;
    }
    let html = '';
    let current = '';
    list.forEach(x => {
      if (x.cat !== current) {
        current = x.cat;
        html += `<div class="letter-head">${current}</div>`;
      }
      html += `<dl class="term"><dt>${x.t}<small>${x.en}</small></dt><dd>${x.d}</dd></dl>`;
    });
    root.innerHTML = html;
  }

  chips.forEach(chip => {
    chip.addEventListener('click', () => {
      chips.forEach(c => c.classList.remove('active'));
      chip.classList.add('active');
      cat = chip.dataset.cat;
      render();
    });
  });
  if (input) input.addEventListener('input', () => { q = input.value.trim(); render(); });
  render();
})();
